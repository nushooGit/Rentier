const messages: Record<AppLocale, Record<TranslationKey, string>> = { ro, en };

export function translateKey(
    key: TranslationKey,
    locale: AppLocale = currentAppLocale(),
    params: Record<string, string | number> = {},
) {
    let value = messages[locale][key] ?? ro[key];

    for (const [name, replacement] of Object.entries(params)) {
        value = value.replaceAll(`{${name}}`, String(replacement));
    }

    return value;
}

export function useI18n() {
    const page = usePage();
    const locale = normalizeAppLocale(
        typeof page.props.locale === 'string' ? page.props.locale : null,
    );

    return {
        locale,
        t: (key: TranslationKey, params: Record<string, string | number> = {}) =>
            translateKey(key, locale, params),
        translate: (value?: string) =>
            value && value in ro
                ? messages[locale][value as TranslationKey]
                : (value ?? ''),
    };
}

